public class AutoEntityDataHelper {

    private static int lastGeneratedCount = -1;

    public static List<EntityData> createAutoEntityData(Collection<EntityData> dataPackEntries) {
        List<EntityData> generated = new ArrayList<>();
        if(!CagedMobsReborn.SERVER_CONFIG.isAutoEntityDataEnabled()){
            return generated;
        }
        Set<EntityType<?>> defined = new HashSet<>();
        for(EntityData data : dataPackEntries){
            if(data != null && data.getEntityType() != null){
                defined.add(data.getEntityType());
            }
        }
        for(EntityType<?> type : BuiltInRegistries.ENTITY_TYPE){
            if(defined.contains(type) || !isAutoEligible(type)){
                continue;
            }
            double health = getDefaultMaxHealth(type);
            generated.add(EntityData.createAutoGenerated(type, String.valueOf(EntityType.getKey(type)), getGrowTicks(health), requiresWater(type), getSamplerTierFromHealth(health)));
        }
        if(generated.size() != lastGeneratedCount){
            lastGeneratedCount = generated.size();
            CagedMobsReborn.LOGGER.debug("[AUTO-ENTITY] Generated {} automatic entity data entries ({} defined by data packs)", generated.size(), defined.size());
        }
        return generated;
    }

    public static boolean isAutoEligible(EntityType<?> type) {
        if(type == EntityTypes.PLAYER || type == EntityTypes.ARMOR_STAND || !type.canSummon()){
            return false;
        }
        if(!DefaultAttributes.hasSupplier(type) || type.getDefaultLootTable().isEmpty()){
            return false;
        }
        if(CagedMobsReborn.SERVER_CONFIG.ifAutoEntityDataExcludesBosses() && type.builtInRegistryHolder().is(Tags.EntityTypes.BOSSES)){
            return false;
        }
        return !CagedMobsReborn.SERVER_CONFIG.getAutoEntityDataBlacklist().contains(String.valueOf(EntityType.getKey(type)));
    }

    @SuppressWarnings("unchecked")
    public static double getDefaultMaxHealth(EntityType<?> type) {
        AttributeSupplier supplier = DefaultAttributes.getSupplier((EntityType<? extends LivingEntity>) type);
        if(supplier != null && supplier.hasAttribute(Attributes.MAX_HEALTH)){
            return supplier.getBaseValue(Attributes.MAX_HEALTH);
        }
        return 20.0;
    }

    public static int getSamplerTierFromHealth(double health) {
        if(health <= CagedMobsReborn.SERVER_CONFIG.getNormalSamplerMaxHealth()){
            return 1;
        }
        if(health <= CagedMobsReborn.SERVER_CONFIG.getDiamondSamplerMaxHealth()){
            return 2;
        }
        return 3;
    }

    public static int getRequiredSamplerTier(EntityData data, Entity target) {
        if(data.isAutoGenerated() && CagedMobsReborn.SERVER_CONFIG.isSamplerTierByCurrentHealth() && target instanceof LivingEntity living){
            return getSamplerTierFromHealth(living.getHealth());
        }
        return data.getSamplerTier();
    }

    public static int getGrowTicks(double health) {
        int min = Math.min(CagedMobsReborn.SERVER_CONFIG.getAutoMinGrowTicks(), CagedMobsReborn.SERVER_CONFIG.getAutoMaxGrowTicks());
        int max = Math.max(CagedMobsReborn.SERVER_CONFIG.getAutoMinGrowTicks(), CagedMobsReborn.SERVER_CONFIG.getAutoMaxGrowTicks());
        double ticks = max - (max - min) * Math.exp(-Math.max(0.0, health) / CagedMobsReborn.SERVER_CONFIG.getAutoGrowHealthScale());
        return Math.max(1, (int) Math.round(ticks));
    }

    private static boolean requiresWater(EntityType<?> type) {
        MobCategory category = type.getCategory();
        return category == MobCategory.WATER_CREATURE || category == MobCategory.WATER_AMBIENT
                || category == MobCategory.UNDERGROUND_WATER_CREATURE || category == MobCategory.AXOLOTLS;
    }

    public static List<ItemStack> rollLoot(ServerLevel level, BlockPos pos, Entity lootEntity, int lootingLevel, boolean onFire) {
        if(!(lootEntity instanceof LivingEntity living)){
            return List.of();
        }
        Optional<ResourceKey<LootTable>> lootTableKey = living.getLootTable();
        if(lootTableKey.isEmpty()){
            return List.of();
        }
        LootTable table = level.getServer().reloadableRegistries().getLootTable(lootTableKey.get());
        if(table == LootTable.EMPTY){
            return List.of();
        }
        FakePlayer player = FakePlayerFactory.getMinecraft(level);
        ItemStack weapon = new ItemStack(Items.IRON_SWORD);
        if(lootingLevel > 0){
            Holder<Enchantment> looting = level.registryAccess().lookupOrThrow(Registries.ENCHANTMENT).getOrThrow(Enchantments.LOOTING);
            weapon.enchant(looting, lootingLevel);
        }
        ItemStack previousItem = player.getMainHandItem();
        player.setItemInHand(InteractionHand.MAIN_HAND, weapon);
        living.setRemainingFireTicks(onFire ? 100 : 0);
        try{
            LootParams params = new LootParams.Builder(level)
                    .withParameter(LootContextParams.THIS_ENTITY, living)
                    .withParameter(LootContextParams.ORIGIN, Vec3.atCenterOf(pos))
                    .withParameter(LootContextParams.DAMAGE_SOURCE, level.damageSources().playerAttack(player))
                    .withOptionalParameter(LootContextParams.ATTACKING_ENTITY, player)
                    .withOptionalParameter(LootContextParams.DIRECT_ATTACKING_ENTITY, player)
                    .withOptionalParameter(LootContextParams.LAST_DAMAGE_PLAYER, player)
                    .create(LootContextParamSets.ENTITY);
            List<ItemStack> drops = table.getRandomItems(params);
            CagedMobsReborn.LOGGER.debug("[AUTO-ENTITY] Rolled loot table {} for {} (looting {}, onFire {}): {}", lootTableKey.get().identifier(), EntityType.getKey(living.getType()), lootingLevel, onFire, drops);
            return drops;
        }finally{
            player.setItemInHand(InteractionHand.MAIN_HAND, previousItem);
            living.setRemainingFireTicks(0);
        }
    }
}
